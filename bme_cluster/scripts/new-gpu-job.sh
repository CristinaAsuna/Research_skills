#!/usr/bin/env bash
set -euo pipefail

usage() {
  cat <<'EOF'
Usage: new-gpu-job.sh OUTPUT_SCRIPT JOB_NAME ENV_ACTIVATION COMMAND [QUEUE] [GPU_TYPE] [MEMORY] [WALL_TIME] [GPU_COUNT] [NODE]

Creates a BME GPU sbatch script. NODE is optional; pass an empty string to omit it.
Examples:
  new-gpu-job.sh jobs/train.sh train-v1 'source activate pytorch' 'python train.py --config base.yaml' bme_gpu NVIDIAA100-PCIE-40GB 64G 96:00:00 2
  new-gpu-job.sh jobs/eval.sh eval-v1 'source /path/to/.venv/bin/activate' 'python eval.py' bme_a10080g NVIDIAA10080GBPCIe 64G 24:00:00 1
EOF
}

if (( $# < 4 || $# > 10 )); then
  usage >&2
  exit 2
fi

output=$1
job_name=$2
env_activation=$3
command=$4
queue=${5:-bme_gpu}
gpu_type=${6:-}
memory=${7:-32G}
wall_time=${8:-96:00:00}
gpu_count=${9:-1}
node=${10:-}

case "$queue" in
  bme_gpu)
    [[ $gpu_count =~ ^[12]$ ]] || { printf 'bme_gpu permits 1 or 2 GPUs.\n' >&2; exit 2; }
    case "$gpu_type" in NVIDIAA10080GBPCIe|NVIDIAA100-PCIE-40GB|TeslaV100-SXM2-32GB|TeslaV100S-PCIE-32GB) ;; *) printf 'bme_gpu requires one of: NVIDIAA10080GBPCIe, NVIDIAA100-PCIE-40GB, TeslaV100-SXM2-32GB, TeslaV100S-PCIE-32GB.\n' >&2; exit 2;; esac
    ;;
  bme_a10080g)
    [[ $gpu_count == 1 && $gpu_type == NVIDIAA10080GBPCIe ]] || { printf 'bme_a10080g permits exactly 1 NVIDIAA10080GBPCIe GPU.\n' >&2; exit 2; }
    ;;
  bme_gpupub)
    [[ $gpu_count == 1 && $gpu_type == TeslaV100-SXM2-32GB ]] || { printf 'bme_gpupub permits exactly 1 TeslaV100-SXM2-32GB GPU.\n' >&2; exit 2; }
    ;;
  *) printf 'Unsupported queue: %s\n' "$queue" >&2; exit 2 ;;
esac

if [[ $wall_time =~ ^([0-9]{1,3}):[0-5][0-9]:[0-5][0-9]$ ]] && (( 10#${BASH_REMATCH[1]} <= 120 )); then
  :
else
  printf 'WALL_TIME must be HH:MM:SS and no more than 120:00:00.\n' >&2
  exit 2
fi

mkdir -p "$(dirname "$output")" "$(dirname "$output")/logs"
{
  printf '%s\n' '#!/bin/bash'
  printf '%s\n' '# Generated by bme-cluster/scripts/new-gpu-job.sh. Compute nodes have no network.'
  printf '#SBATCH -J %s\n#SBATCH -N 1\n#SBATCH -p %s\n#SBATCH -n 8\n#SBATCH --mem=%s\n#SBATCH --gres=gpu:%s:%s\n' "$job_name" "$queue" "$memory" "$gpu_type" "$gpu_count"
  if [[ -n $node ]]; then printf '#SBATCH -w %s\n' "$node"; fi
  printf '#SBATCH -t %s\n#SBATCH -o %s/logs/%%x-%%j.out\n#SBATCH -e %s/logs/%%x-%%j.err\n\n' "$wall_time" "$(dirname "$output")" "$(dirname "$output")"
  printf '%s\n' 'set -eo pipefail' 'echo "${SLURM_JOB_NODELIST}"' 'nvidia-smi' 'echo "start on $(date)"'
  printf '%s\n%s\necho "end on $(date)"\n' "$env_activation" "$command"
} > "$output"
chmod u+x "$output"
printf 'Created %s\nReview it, then submit with: sbatch %s\n' "$output" "$output"
