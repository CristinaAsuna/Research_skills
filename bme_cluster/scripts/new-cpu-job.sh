#!/usr/bin/env bash
set -euo pipefail

usage() {
  cat <<'EOF'
Usage: new-cpu-job.sh OUTPUT_SCRIPT JOB_NAME ENV_ACTIVATION COMMAND [CPU_COUNT] [MEMORY] [WALL_TIME] [NODE]

Creates a BME CPU sbatch script. NODE is optional; pass an empty string to omit it.
Examples:
  new-cpu-job.sh jobs/preprocess.sh preprocess 'source ~/.bashrc && conda activate pytorch' 'python preprocess.py' 8 32G 96:00:00
  new-cpu-job.sh jobs/eval.sh eval 'source /path/to/.venv/bin/activate' 'python eval.py' 16 64G 24:00:00 cpu-node-01
EOF
}

if (( $# < 4 || $# > 8 )); then
  usage >&2
  exit 2
fi

output=$1
job_name=$2
env_activation=$3
command=$4
cpu_count=${5:-8}
memory=${6:-32G}
wall_time=${7:-96:00:00}
node=${8:-}

[[ $cpu_count =~ ^[1-9][0-9]*$ ]] || { printf 'CPU_COUNT must be a positive integer.\n' >&2; exit 2; }

if [[ $wall_time =~ ^([0-9]{1,3}):[0-5][0-9]:[0-5][0-9]$ ]] && (( 10#${BASH_REMATCH[1]} <= 120 )); then
  :
else
  printf 'WALL_TIME must be HH:MM:SS and no more than 120:00:00.\n' >&2
  exit 2
fi

mkdir -p "$(dirname "$output")" "$(dirname "$output")/logs"
{
  printf '%s\n' '#!/bin/bash'
  printf '%s\n' '# Generated by bme-cluster/scripts/new-cpu-job.sh. Compute nodes have no network.'
  printf '#SBATCH -J %s\n#SBATCH -N 1\n#SBATCH -p bme_cpu\n#SBATCH -n %s\n#SBATCH --mem=%s\n' "$job_name" "$cpu_count" "$memory"
  if [[ -n $node ]]; then printf '#SBATCH -w %s\n' "$node"; fi
  printf '#SBATCH -t %s\n#SBATCH -o %s/logs/%%x-%%j.out\n#SBATCH -e %s/logs/%%x-%%j.err\n\n' "$wall_time" "$(dirname "$output")" "$(dirname "$output")"
  printf '%s\n' 'set -eo pipefail' 'echo "${SLURM_JOB_NODELIST}"' 'echo "start on $(date)"'
  printf '%s\n%s\necho "end on $(date)"\n' "$env_activation" "$command"
} > "$output"
chmod u+x "$output"
printf 'Created %s\nReview it, then submit with: sbatch %s\n' "$output" "$output"
